#!/usr/bin/env python3
"""Generate UI permission hints from the backend source of truth; server remains authoritative."""
from pathlib import Path
import re, json
root = Path(__file__).resolve().parents[3]
s = (root/'packages/contracts/src/permissions.ts').read_text()
all_permissions = re.findall(r"'([^']+)'", s.split('export const PERMISSIONS = [')[1].split('] as const')[0])
roles = s.split('export const ROLE_PERMISSIONS:')[1].split('\n};')[0]
output = ['// Generated by scripts/generate_permissions.py; do not hand edit.', 'public enum Permissions {', '    private static let roles: [String: Set<String>] = [']
for role, expression in re.findall(r'  (\w+): (all|without\([\s\S]*?\)|\[[\s\S]*?\])[,\n]', roles):
    values = re.findall(r"'([^']+)'", expression)
    if expression == 'all': values = all_permissions
    elif expression.startswith('without'): values = [p for p in all_permissions if p not in values]
    output.append('        '+json.dumps(role)+': Set('+json.dumps(values)+'),')
output += ['    ]', '    public static func can(_ role: String, _ permission: String) -> Bool {', '        roles[role]?.contains(permission) == true', '    }', '}']
(root/'apps/ipad-pos/Sources/ResutoCore/Permissions.swift').write_text('\n'.join(output)+'\n')
