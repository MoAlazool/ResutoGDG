#!/usr/bin/env python3
"""Seeded SYNTHETIC restaurant dataset generator (Egypt + Saudi Arabia patterns).

!!! SYNTHETIC DATA — generated by this script, not collected from any restaurant. !!!
It exists so the research pipelines are reproducible before real, consented data is available.
Results computed on it demonstrate that the pipelines work; they are not evidence of real-world
performance. Every output file carries the SYNTHETIC label (manifest.json, datasheet) and the
API stores evaluations derived from it with ``is_synthetic_data = true``.

Modelled patterns (parameters in DEFAULT_CONFIG, recorded in manifest.json):
* Friday–Saturday weekend (both countries) with a Thursday-evening uplift.
* Meal peaks: lunch (~14:00) and dinner (~21:00) plus a late-night tail.
* Ramadan: lower daytime demand, iftar peak just after sunset (~18:20) and a suhoor peak (~02:00),
  higher delivery share, seasonal specials (qatayef, kunafa, sobia) and an Eid al-Fitr uplift.
* Customers with heterogeneous visit rates (gamma), join dates and latent churn dates
  (exponential lifetimes), favourite dishes (repeat purchases) and main→side affinities (co-occurrence).
* Delivery drop-offs around each branch (gamma-distributed radius).

Usage: python research/data/generate_synthetic.py [--seed 2026] [--out research/data/synthetic/resuto-synth-v1]
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

import numpy as np

DATASET_NAME = "resuto-synth-v1"
LABEL = "SYNTHETIC — generated by research/data/generate_synthetic.py; not real restaurant data"

DEFAULT_CONFIG = {
    "seed": 2026,
    "start": "2024-01-01",
    "end": "2025-06-30",
    "branches": [
        {"id": "cai-01", "country": "EG", "city": "Cairo", "timezone": "Africa/Cairo", "currency": "EGP",
         "lat": 30.0444, "lng": 31.2357, "baseOrdersPerDay": 105, "customers": 2600, "priceScale": 1.0},
        {"id": "ruh-01", "country": "SA", "city": "Riyadh", "timezone": "Asia/Riyadh", "currency": "SAR",
         "lat": 24.7136, "lng": 46.6753, "baseOrdersPerDay": 85, "customers": 2000, "priceScale": 0.16},
    ],
    # Monday..Sunday multipliers; Fri/Sat weekend, Thursday is the weekend eve.
    "dowMultiplier": [0.92, 0.93, 0.98, 1.22, 1.30, 1.15, 0.90],
    "ramadan": [["2024-03-11", "2024-04-09"], ["2025-03-01", "2025-03-29"]],
    "eid": [["2024-04-10", "2024-04-12"], ["2025-03-30", "2025-04-01"]],
    "ramadanVolumeMultiplier": 0.88,
    "eidVolumeMultiplier": 1.35,
    "annualGrowth": 0.08,
    "seasonalAmplitude": 0.05,
    "dailyDispersionK": 25.0,          # negative binomial shape for daily order counts
    "registeredShare": 0.58,           # share of orders linked to a known customer
    "fulfillmentShare": {"dine_in": 0.45, "pickup": 0.20, "delivery": 0.35},
    "ramadanDeliveryShare": 0.50,
    "customerRateGamma": [0.9, 1.0],   # shape, scale (relative visit propensity)
    "customerMeanLifetimeDays": 320,
    "customersPresentAtStart": 0.35,
    "favouriteMainProb": 0.5,
    "sideProb": 0.62, "drinkProb": 0.7, "dessertProb": 0.14, "ramadanDessertProb": 0.38,
    "deliveryRadiusGammaKm": [2.2, 1.4],  # shape, scale → mean ≈ 3.1 km
    "maxDeliveryKm": 9.0,
}

# id, category, english name (for human inspection only; models use ids), EGP price (minor units)
MENU = [
    ("m01", "main", "Koshary bowl", 6500), ("m02", "main", "Grilled kofta plate", 16500),
    ("m03", "main", "Chicken shawarma wrap", 9500), ("m04", "main", "Beef shawarma plate", 17500),
    ("m05", "main", "Molokhia with rice", 12000), ("m06", "main", "Mixed grill", 29500),
    ("m07", "main", "Smash burger", 18500), ("m08", "main", "Fattah", 15500),
    ("m09", "main", "Chicken mandi", 21000), ("m10", "main", "Falafel sandwich", 3500),
    ("s01", "side", "Fries", 4500), ("s02", "side", "Tahini salad", 3000), ("s03", "side", "Baba ghanoush", 4000),
    ("s04", "side", "Green salad", 3500), ("s05", "side", "Lentil soup", 5000), ("s06", "side", "Pickles", 1500),
    ("d01", "drink", "Soda", 2500), ("d02", "drink", "Water", 1000), ("d03", "drink", "Fresh mango juice", 5500),
    ("d04", "drink", "Hibiscus (karkade)", 3000), ("d05", "drink", "Arabic coffee", 3500), ("d06", "drink", "Sobia", 4000),
    ("x01", "dessert", "Om Ali", 7000), ("x02", "dessert", "Basbousa", 5000), ("x03", "dessert", "Rice pudding", 4500),
    ("x04", "dessert", "Qatayef", 6000), ("x05", "dessert", "Kunafa", 8000), ("x06", "dessert", "Ice cream", 4000),
]
RAMADAN_SPECIALS = {"x04", "x05", "d06"}
# Each main has a preferred side and drink (co-occurrence structure).
MAIN_SIDE_AFFINITY = {"m01": "s05", "m02": "s02", "m03": "s01", "m04": "s02", "m05": "s04", "m06": "s03",
                      "m07": "s01", "m08": "s06", "m09": "s04", "m10": "s02"}
MAIN_DRINK_AFFINITY = {"m01": "d04", "m02": "d01", "m03": "d01", "m04": "d03", "m05": "d02", "m06": "d03",
                       "m07": "d01", "m08": "d04", "m09": "d05", "m10": "d02"}


def daterange(a: date, b: date):
    d = a
    while d <= b:
        yield d
        d += timedelta(days=1)


def in_ranges(d: date, ranges) -> bool:
    return any(date.fromisoformat(a) <= d <= date.fromisoformat(b) for a, b in ranges)


def sample_hour(rng, ramadan: bool) -> float:
    if ramadan:
        comps = [(18.35, 0.45, 0.55), (22.0, 1.2, 0.27), (26.0, 0.8, 0.18)]  # iftar, evening, suhoor (02:00 next day)
    else:
        comps = [(14.0, 1.2, 0.40), (21.0, 1.5, 0.50), (24.6, 0.9, 0.10)]
    w = np.array([c[2] for c in comps])
    i = rng.choice(len(comps), p=w / w.sum())
    mu, sd, _ = comps[i]
    return float(np.clip(rng.normal(mu, sd), 10.0, 27.9))  # 10:00 .. 03:54 next day


def generate(config: dict, out: Path) -> dict:
    rng = np.random.default_rng(config["seed"])
    start, end = date.fromisoformat(config["start"]), date.fromisoformat(config["end"])
    n_days = (end - start).days + 1
    out.mkdir(parents=True, exist_ok=True)
    items = {m[0]: m for m in MENU}
    mains = [m[0] for m in MENU if m[1] == "main"]
    sides = [m[0] for m in MENU if m[1] == "side"]
    drinks = [m[0] for m in MENU if m[1] == "drink" and m[0] not in RAMADAN_SPECIALS]
    desserts = [m[0] for m in MENU if m[1] == "dessert" and m[0] not in RAMADAN_SPECIALS]
    zipf = lambda n: (lambda w: w / w.sum())(1 / np.arange(1, n + 1) ** 0.8)  # noqa: E731
    main_w = zipf(len(mains))

    customers_rows, orders_rows, lines_rows = [], [], []
    order_seq = 0
    for b in config["branches"]:
        tz = ZoneInfo(b["timezone"])
        n_c = b["customers"]
        shape, scale = config["customerRateGamma"]
        rate = rng.gamma(shape, scale, n_c)
        present = rng.random(n_c) < config["customersPresentAtStart"]
        join = np.where(present, 0, rng.integers(0, n_days, n_c))
        life = rng.exponential(config["customerMeanLifetimeDays"], n_c)
        churn = join + life  # day index after which the customer never orders again (latent)
        fav = rng.choice(mains, size=n_c, p=main_w)
        rad = np.minimum(rng.gamma(*config["deliveryRadiusGammaKm"], n_c), config["maxDeliveryKm"])
        ang = rng.uniform(0, 2 * math.pi, n_c)
        home_lat = b["lat"] + rad * np.cos(ang) / 111.0
        home_lng = b["lng"] + rad * np.sin(ang) / (111.0 * math.cos(math.radians(b["lat"])))
        cids = [f"{b['id']}-c{i:05d}" for i in range(n_c)]
        for i in range(n_c):
            customers_rows.append({
                "customer_id": cids[i], "branch_id": b["id"], "joined_on": (start + timedelta(days=int(join[i]))).isoformat(),
                "latent_churn_on": (start + timedelta(days=int(churn[i]))).isoformat() if churn[i] < n_days else "",
                "home_lat": round(float(home_lat[i]), 6), "home_lng": round(float(home_lng[i]), 6), "favourite_item": fav[i],
            })

        for di, d in enumerate(daterange(start, end)):
            ram = in_ranges(d, config["ramadan"])
            eid = in_ranges(d, config["eid"])
            mult = config["dowMultiplier"][d.weekday()]
            mult *= 1 + config["annualGrowth"] * di / 365
            mult *= 1 + config["seasonalAmplitude"] * math.sin(2 * math.pi * (d.timetuple().tm_yday - 80) / 365)
            if ram:
                mult *= config["ramadanVolumeMultiplier"]
            if eid:
                mult *= config["eidVolumeMultiplier"]
            mu = b["baseOrdersPerDay"] * mult
            k = config["dailyDispersionK"]
            n_orders = int(rng.poisson(rng.gamma(k, mu / k)))
            active = np.where((join <= di) & (churn > di))[0]
            p_active = rate[active] / rate[active].sum() if active.size else None
            fshare = dict(config["fulfillmentShare"])
            if ram:
                fshare = {"dine_in": 0.32, "pickup": 1 - 0.32 - config["ramadanDeliveryShare"], "delivery": config["ramadanDeliveryShare"]}
            fkeys = list(fshare)
            fprobs = np.array([fshare[x] for x in fkeys])
            for _ in range(n_orders):
                order_seq += 1
                oid = f"o{order_seq:07d}"
                cust = None
                if active.size and rng.random() < config["registeredShare"]:
                    cust = int(rng.choice(active, p=p_active))
                h = sample_hour(rng, ram)
                local = datetime(d.year, d.month, d.day, tzinfo=tz) + timedelta(hours=h)
                local = local.replace(tzinfo=None).replace(tzinfo=tz)  # normalise offset after crossing DST changes
                fulfillment = fkeys[int(rng.choice(len(fkeys), p=fprobs))]
                party = 1 + int(rng.poisson(0.7))
                basket: dict[str, int] = {}
                for _p in range(party):
                    if cust is not None and rng.random() < config["favouriteMainProb"]:
                        main = fav[cust]
                    else:
                        main = mains[int(rng.choice(len(mains), p=main_w))]
                    basket[main] = basket.get(main, 0) + 1
                    if rng.random() < config["sideProb"]:
                        s = MAIN_SIDE_AFFINITY[main] if rng.random() < 0.6 else sides[int(rng.integers(len(sides)))]
                        basket[s] = basket.get(s, 0) + 1
                    if rng.random() < config["drinkProb"]:
                        if ram and rng.random() < 0.35:
                            dr = "d06"
                        else:
                            dr = MAIN_DRINK_AFFINITY[main] if rng.random() < 0.5 else drinks[int(rng.integers(len(drinks)))]
                        basket[dr] = basket.get(dr, 0) + 1
                p_dessert = config["ramadanDessertProb"] if ram else config["dessertProb"]
                if rng.random() < p_dessert:
                    pool = ["x04", "x05", "x01"] if ram else desserts
                    x = pool[int(rng.integers(len(pool)))]
                    basket[x] = basket.get(x, 0) + 1
                total = 0
                for item, q in basket.items():
                    unit = int(round(items[item][3] * b["priceScale"] / 100) * 100) if b["priceScale"] != 1 else items[item][3]
                    total += unit * q
                    lines_rows.append({"order_id": oid, "item_id": item, "quantity": q, "unit_price_minor": unit})
                business = (local - timedelta(hours=4)).date()
                drop_lat = drop_lng = ""
                if fulfillment == "delivery":
                    if cust is not None:
                        drop_lat, drop_lng = round(float(home_lat[cust]), 6), round(float(home_lng[cust]), 6)
                    else:
                        r = min(float(rng.gamma(*config["deliveryRadiusGammaKm"])), config["maxDeliveryKm"])
                        a = float(rng.uniform(0, 2 * math.pi))
                        drop_lat = round(b["lat"] + r * math.cos(a) / 111.0, 6)
                        drop_lng = round(b["lng"] + r * math.sin(a) / (111.0 * math.cos(math.radians(b["lat"]))), 6)
                orders_rows.append({
                    "order_id": oid, "branch_id": b["id"], "customer_id": cids[cust] if cust is not None else "",
                    "placed_at": local.isoformat(timespec="seconds"), "business_date": business.isoformat(),
                    "fulfillment": fulfillment, "total_minor": total, "currency": b["currency"],
                    "dropoff_lat": drop_lat, "dropoff_lng": drop_lng,
                })

    tables = {
        "items.csv": [{"item_id": m[0], "category": m[1], "name_en": m[2], "price_minor_egp": m[3],
                       "ramadan_special": int(m[0] in RAMADAN_SPECIALS)} for m in MENU],
        "branches.csv": [{k: b[k] for k in ("id", "country", "city", "timezone", "currency", "lat", "lng")} for b in config["branches"]],
        "customers.csv": customers_rows,
        "orders.csv": orders_rows,
        "order_lines.csv": lines_rows,
    }
    files = {}
    for name, rows in tables.items():
        path = out / name
        with path.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        files[name] = {"rows": len(rows), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    manifest = {"dataset": DATASET_NAME, "kind": "synthetic", "isSyntheticData": True, "label": LABEL,
                "generator": "research/data/generate_synthetic.py", "config": config, "files": files}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (out / "SYNTHETIC_DATA_README.txt").write_text(LABEL + "\nSee research/data/DATASHEET.md.\n")
    return manifest


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=DEFAULT_CONFIG["seed"])
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "synthetic" / DATASET_NAME)
    args = ap.parse_args()
    cfg = {**DEFAULT_CONFIG, "seed": args.seed}
    m = generate(cfg, args.out)
    print(json.dumps({k: v for k, v in m.items() if k != "config"}, indent=2))


if __name__ == "__main__":
    main()
