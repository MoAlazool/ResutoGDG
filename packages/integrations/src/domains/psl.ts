// Public Suffix List lookups for custom domains (INT-27).
//
// "brand.com.eg" is the registrable domain (apex) of its zone even though it has three labels: "com.eg" is a public
// suffix. An apex cannot carry a CNAME (RFC 1034 §3.6.2: a CNAME cannot coexist with the SOA/NS records every zone apex
// has), so the routing record depends on getting this right.
// Algorithm: https://github.com/publicsuffix/list/wiki/Format#algorithm (exception rules beat wildcard and normal
// rules; the longest matching rule wins; with no match the default rule "*" applies).
// Data: ./psl-icann.ts (the whole ICANN section), generated by scripts/providers/update-psl.mjs from the official list.
import { PSL_RULES, PSL_VERSION } from './psl-icann';

const NORMAL = new Set<string>();
const WILDCARD = new Set<string>(); // "*.ck" stored as "ck"
const EXCEPTION = new Set<string>(); // "!www.ck" stored as "www.ck"
for (const r of PSL_RULES) {
  if (r.startsWith('!')) EXCEPTION.add(r.slice(1));
  else if (r.startsWith('*.')) WILDCARD.add(r.slice(2));
  else NORMAL.add(r);
}

export interface DomainParts {
  hostname: string;
  /** The public suffix ("com.eg"). */
  publicSuffix: string;
  /** The registrable domain ("brand.com.eg"), or null when the hostname is itself a public suffix. */
  registrableDomain: string | null;
  /** True when the hostname is the registrable domain (the zone apex): it needs an A record, not a CNAME. */
  isApex: boolean;
  /** The rules the answer comes from: the full ICANN section of the bundled list (exact for every TLD). */
  pslCoverage: 'icann';
  pslVersion: string;
}

/** Lower-cases, strips one trailing dot and validates LDH labels (IDNs must already be in punycode). */
export function normaliseHostname(input: string): string {
  const h = input.trim().toLowerCase().replace(/\.$/, '');
  const labels = h.split('.');
  if (h.length > 253 || labels.length < 2 || labels.some((l) => !/^(?!-)[a-z0-9-]{1,63}(?<!-)$/.test(l))) throw new RangeError(`invalid hostname "${input.slice(0, 80)}"`);
  return h;
}

/** Public-suffix breakdown of a hostname. */
export function domainParts(input: string): DomainParts {
  const hostname = normaliseHostname(input);
  const labels = hostname.split('.');
  // Longest matching rule, measured in labels; the default rule "*" matches one label.
  let suffixLabels = 1;
  for (let i = 0; i < labels.length; i++) {
    const candidate = labels.slice(i).join('.');
    if (EXCEPTION.has(candidate)) { suffixLabels = labels.length - i - 1; break; }
    const parent = labels.slice(i + 1).join('.');
    if (NORMAL.has(candidate)) suffixLabels = Math.max(suffixLabels, labels.length - i);
    if (parent && WILDCARD.has(parent)) suffixLabels = Math.max(suffixLabels, labels.length - i);
  }
  const publicSuffix = labels.slice(labels.length - suffixLabels).join('.');
  const registrableDomain = labels.length > suffixLabels ? labels.slice(labels.length - suffixLabels - 1).join('.') : null;
  return {
    hostname, publicSuffix, registrableDomain, isApex: registrableDomain === hostname,
    pslCoverage: 'icann', pslVersion: PSL_VERSION,
  };
}

/** True when the hostname is the apex of its registrable domain ("brand.com.eg", "brand.com"), false for "www.brand.com.eg". */
export const isApexDomain = (hostname: string) => domainParts(hostname).isApex;
