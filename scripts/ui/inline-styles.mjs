#!/usr/bin/env node
// Counts inline `style={...}` props per dashboard and admin source file (VS-31 / REM-W11 ratchet).
//
//   node scripts/ui/inline-styles.mjs           print the files with the most inline styles
//   node scripts/ui/inline-styles.mjs --write   refresh apps/web/lib/inline-styles-baseline.json (only after REMOVING some)
//
// apps/web/lib/inline-styles-policy.test.ts fails when a file has more inline styles than its baseline entry (use a
// shared component, a utility class from app/globals.css or a page stylesheet instead), and when a file has FEWER than
// its entry, so every improvement is locked in with --write. Values computed at run time (a chart bar's width, a
// floor object's position) are legitimate inline styles; they stay in the count and simply cannot grow.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SCAN = ['apps/web/app/dashboard', 'apps/web/app/admin'];
export const BASELINE = path.join(ROOT, 'apps/web/lib/inline-styles-baseline.json');
const STYLE = /\bstyle=\{/g;

function* files(dir) {
  for (const n of readdirSync(dir)) {
    if (n === 'node_modules' || n.startsWith('.')) continue;
    const p = path.join(dir, n);
    if (statSync(p).isDirectory()) yield* files(p);
    else if (/\.tsx$/.test(n) && !/\.test\.tsx$/.test(n)) yield p;
  }
}

/** { 'apps/web/app/dashboard/…/page.tsx': count } for every scanned file with at least one inline style. */
export function countInlineStyles() {
  const out = {};
  for (const dir of SCAN) for (const f of files(path.join(ROOT, dir))) {
    const rel = path.relative(ROOT, f).split(path.sep).join('/');
    const n = (readFileSync(f, 'utf8').match(STYLE) ?? []).length;
    if (n) out[rel] = n;
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const counts = countInlineStyles();
  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  if (process.argv.includes('--write')) {
    writeFileSync(BASELINE, JSON.stringify({
      $description: 'Inline style props per dashboard/admin file (ratchet). Generated by scripts/ui/inline-styles.mjs --write; counts may only go down.',
      files: counts,
    }, null, 1) + '\n');
    console.log(`wrote ${path.relative(ROOT, BASELINE)}: ${Object.keys(counts).length} files, ${total} inline styles`);
  } else {
    for (const [f, n] of Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 25)) console.log(String(n).padStart(4), f);
    console.log('total', total);
  }
}
