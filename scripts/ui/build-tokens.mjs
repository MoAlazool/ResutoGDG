#!/usr/bin/env node
// Generates packages/ui/src/tokens.css from docs/ui/design-tokens.json ("css" section), the single source of the
// web app's design tokens. Values are literals, {dotted.path} references into the JSON (the extracted legacy values)
// or var(--…) references to other tokens, so a colour is written once.
//
// Tiers (docs/ui/DESIGN_SYSTEM.md):
//   primitive  raw scales (neutral, brand, sand, status hues, type, space, radius, motion)   → :root
//   semantic   roles (--bg, --surface-1..3, --text*, --border*, --accent*, --focus, status, charts, elevation)
//              light values                                                                → :root, [data-theme='light']
//   dark       the same roles in the dark theme (defined, not exposed in the UI yet)        → [data-theme='dark']
//   alias      every pre-2.1 name mapped onto a semantic token or primitive step
//   component  domain palettes (floor states, landing identity, sign-in panel, code, fonts)  → :root, [data-theme]
//   ar         Arabic type adjustments                                                     → html[lang='ar'], [lang='ar']
// Aliases and component tokens are re-declared on every [data-theme] element so a var(--…) alias resolves against the
// theme of the subtree it is used in (custom properties inherit computed values).
//
//   node scripts/ui/build-tokens.mjs          write tokens.css
//   node scripts/ui/build-tokens.mjs --check  exit 1 when tokens.css is stale
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SOURCE = path.join(ROOT, 'docs/ui/design-tokens.json');
export const TARGET = path.join(ROOT, 'packages/ui/src/tokens.css');

/** Tier → selector, in output order. */
export const TIERS = [
  ['primitive', ':root'],
  ['semantic', ":root, [data-theme='light']"],
  ['dark', "[data-theme='dark']"],
  ['alias', ':root, [data-theme]'],
  ['component', ':root, [data-theme]'],
  ['ar', "html[lang='ar'], [lang='ar']"],
];
/** Plain CSS properties a tier may set besides custom properties. */
const PLAIN = new Set(['color-scheme']);

function lookup(json, ref) {
  let cur = json;
  for (const part of ref.split('.')) {
    if (cur === null || typeof cur !== 'object' || !(part in cur)) throw new Error(`design-tokens.json: unresolved reference {${ref}}`);
    cur = cur[part];
  }
  if (typeof cur !== 'string') throw new Error(`design-tokens.json: {${ref}} is not a string value`);
  return cur;
}
export const resolveValue = (json, v) => v.replace(/\{([A-Za-z0-9_.|-]+)\}/g, (_, ref) => lookup(json, ref));

/** The declarations of one tier: [[name, value]] with {refs} resolved ($description and other keys dropped). */
export function tierEntries(json, tier) {
  return Object.entries(json.css?.[tier] ?? {}).filter(([k]) => k.startsWith('--') || PLAIN.has(k)).map(([k, v]) => [k, resolveValue(json, v)]);
}

/** Every custom property defined anywhere, and the var(--…) names that are referenced but never defined. */
export function undefinedReferences(json) {
  const defined = new Set(TIERS.flatMap(([t]) => tierEntries(json, t).map(([k]) => k)));
  const missing = new Set();
  for (const [t] of TIERS) for (const [, v] of tierEntries(json, t)) for (const m of v.matchAll(/var\((--[\w-]+)/g)) if (!defined.has(m[1])) missing.add(m[1]);
  return [...missing];
}

export function renderTokens(json) {
  const css = json.css;
  if (!css?.primitive || !css?.semantic) throw new Error('design-tokens.json: missing "css.primitive" or "css.semantic"');
  const missing = undefinedReferences(json);
  if (missing.length) throw new Error(`design-tokens.json: var() references to undefined tokens: ${missing.join(', ')}`);
  const seen = new Map();
  for (const [t] of TIERS.filter(([t]) => ['primitive', 'semantic', 'alias', 'component'].includes(t))) {
    for (const [k] of tierEntries(json, t)) {
      if (seen.has(k)) throw new Error(`design-tokens.json: ${k} is defined in both "${seen.get(k)}" and "${t}"`);
      seen.set(k, t);
    }
  }
  const block = (tier, sel) => {
    const rows = tierEntries(json, tier);
    return rows.length ? `/* ${tier} */\n${sel} {\n${rows.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n` : '';
  };
  return [
    '/*',
    ' * Resuto design tokens. GENERATED by scripts/ui/build-tokens.mjs from docs/ui/design-tokens.json ("css").',
    ' * Do not edit by hand: change the JSON and run `node scripts/ui/build-tokens.mjs`.',
    ' * Tiers: primitive scales → semantic roles (light; dark under [data-theme=dark]) → aliases for every pre-2.1 name and',
    ' * component palettes (floor states, landing identity, sign-in panel). Use semantic names in new code',
    ' * (docs/ui/DESIGN_SYSTEM.md); scripts/ui/contrast.mjs checks the text/background pairs against WCAG 2.2 AA.',
    ' */',
    ...TIERS.map(([tier, sel]) => block(tier, sel)).filter(Boolean),
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const json = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const out = renderTokens(json);
  if (process.argv.includes('--check')) {
    const cur = readFileSync(TARGET, 'utf8');
    if (cur !== out) { console.error('packages/ui/src/tokens.css is stale: run node scripts/ui/build-tokens.mjs'); process.exit(1); }
    console.log('tokens.css is up to date');
  } else {
    writeFileSync(TARGET, out);
    const counts = TIERS.map(([t]) => `${t} ${tierEntries(json, t).length}`).join(', ');
    console.log(`wrote ${path.relative(ROOT, TARGET)} (${counts})`);
  }
}
