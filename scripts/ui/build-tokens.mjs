#!/usr/bin/env node
// Generates packages/ui/src/tokens.css from docs/ui/design-tokens.json ("css" section), the single source of the
// web app's design tokens. Values are literals or {dotted.path} references into the JSON (the extracted legacy
// values), so a legacy colour is written once.
//
//   node scripts/ui/build-tokens.mjs          write tokens.css
//   node scripts/ui/build-tokens.mjs --check  exit 1 when tokens.css is stale
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SOURCE = path.join(ROOT, 'docs/ui/design-tokens.json');
export const TARGET = path.join(ROOT, 'packages/ui/src/tokens.css');

function lookup(json, ref) {
  let cur = json;
  for (const part of ref.split('.')) {
    if (cur === null || typeof cur !== 'object' || !(part in cur)) throw new Error(`design-tokens.json: unresolved reference {${ref}}`);
    cur = cur[part];
  }
  if (typeof cur !== 'string') throw new Error(`design-tokens.json: {${ref}} is not a string value`);
  return cur;
}
const resolveValue = (json, v) => v.replace(/\{([A-Za-z0-9_.|-]+)\}/g, (_, ref) => lookup(json, ref));

export function renderTokens(json) {
  const css = json.css;
  if (!css?.root) throw new Error('design-tokens.json: missing "css.root"');
  const block = (sel, vars) => `${sel} {\n${Object.entries(vars).filter(([k]) => k.startsWith('--')).map(([k, v]) => `  ${k}: ${resolveValue(json, v)};`).join('\n')}\n}\n`;
  return [
    '/*',
    ' * Resuto design tokens. GENERATED by scripts/ui/build-tokens.mjs from docs/ui/design-tokens.json ("css").',
    ' * Do not edit by hand: change the JSON and run `node scripts/ui/build-tokens.mjs`.',
    ' * brand = landing/booking identity (--brand-*); workspace = staff and guest app; legacy staff layer (--green,',
    ' * --border, nav/shell colours) restores the original manager workspace; --state-* are floor table states.',
    ' */',
    block(':root', css.root),
    css.ar ? block('html[lang=\'ar\'], [lang=\'ar\']', css.ar) : '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = renderTokens(JSON.parse(readFileSync(SOURCE, 'utf8')));
  if (process.argv.includes('--check')) {
    const cur = readFileSync(TARGET, 'utf8');
    if (cur !== out) { console.error('packages/ui/src/tokens.css is stale: run node scripts/ui/build-tokens.mjs'); process.exit(1); }
    console.log('tokens.css is up to date');
  } else {
    writeFileSync(TARGET, out);
    console.log(`wrote ${path.relative(ROOT, TARGET)} (${Object.keys(JSON.parse(readFileSync(SOURCE, 'utf8')).css.root).length} root entries)`);
  }
}
