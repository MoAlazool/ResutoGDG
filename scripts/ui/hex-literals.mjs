#!/usr/bin/env node
// Counts hex colour literals per source file in the web app and the UI package (VS-01 token policy).
//
//   node scripts/ui/hex-literals.mjs           print the files with the most literals
//   node scripts/ui/hex-literals.mjs --write   refresh apps/web/lib/tokens-baseline.json (only after REMOVING literals)
//
// apps/web/lib/tokens-policy.test.ts fails when a file has more literals than its baseline entry, so colours are
// added as tokens in docs/ui/design-tokens.json (→ packages/ui/src/tokens.css) and used through var(--…). It also
// fails when a file has FEWER literals than its entry, so every improvement is locked in with --write.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const SCAN = ['apps/web/app', 'apps/web/components', 'apps/web/lib', 'packages/ui/src'];
/** Exempt: the token file itself and the landing page, a verbatim port of the protected legacy identity. */
export const EXEMPT = [/^packages\/ui\/src\/tokens\.css$/, /^apps\/web\/components\/landing\//, /\.test\.tsx?$/];
export const BASELINE = path.join(ROOT, 'apps/web/lib/tokens-baseline.json');
const HEX = /(?<![\w&])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g;

function* files(dir) {
  for (const n of readdirSync(dir)) {
    if (n === 'node_modules' || n.startsWith('.')) continue;
    const p = path.join(dir, n);
    if (statSync(p).isDirectory()) yield* files(p);
    else if (/\.(css|tsx?|mjs)$/.test(n)) yield p;
  }
}

/** { 'apps/web/…/file.css': count } for every scanned, non-exempt file with at least one literal. */
export function countHexLiterals() {
  const out = {};
  for (const dir of SCAN) for (const f of files(path.join(ROOT, dir))) {
    const rel = path.relative(ROOT, f).split(path.sep).join('/');
    if (EXEMPT.some((re) => re.test(rel))) continue;
    const n = (readFileSync(f, 'utf8').match(HEX) ?? []).length;
    if (n) out[rel] = n;
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const counts = countHexLiterals();
  if (process.argv.includes('--write')) {
    writeFileSync(BASELINE, JSON.stringify({
      $description: 'Hex colour literals per file (ratchet). Generated by scripts/ui/hex-literals.mjs --write; counts may only go down. New colours belong in docs/ui/design-tokens.json.',
      files: counts,
    }, null, 1) + '\n');
    console.log(`wrote ${path.relative(ROOT, BASELINE)}: ${Object.keys(counts).length} files, ${Object.values(counts).reduce((a, b) => a + b, 0)} literals`);
  } else {
    for (const [f, n] of Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 25)) console.log(String(n).padStart(4), f);
    console.log('total', Object.values(counts).reduce((a, b) => a + b, 0));
  }
}
