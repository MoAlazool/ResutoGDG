#!/usr/bin/env node
// Regenerates packages/integrations/src/domains/psl-icann.ts from the Public Suffix List (INT-27).
//
//   curl -sS https://publicsuffix.org/list/public_suffix_list.dat -o /tmp/psl.dat
//   node scripts/providers/update-psl.mjs /tmp/psl.dat
//   pnpm --filter @resuto/integrations test   # domains.test.ts pins the rules Resuto depends on
//
// The whole ICANN section is bundled (every multi-label registry rule: com.eg, com.sa, co.uk, co.jp, com.br …), so apex
// detection is exact for every TLD. Private-domain rules (github.io …) are left out: they are not registries a
// restaurant buys an apex from. Single-label rules are not needed (the PSL default rule "*" already treats every TLD
// as a public suffix). Internationalised rules are stored in punycode (hostnames are validated as punycode).
// The list is downloaded by a person; this script never fetches anything.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, domainToASCII } from 'node:url';

const [, , input] = process.argv;
if (!input) { console.error('usage: node scripts/providers/update-psl.mjs <public_suffix_list.dat>'); process.exit(2); }
const text = readFileSync(input, 'utf8');
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? 'unknown';
const commit = text.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? 'unknown';
const start = text.indexOf('// ===BEGIN ICANN DOMAINS===');
const end = text.indexOf('// ===END ICANN DOMAINS===');
if (start < 0 || end < 0) { console.error('ICANN section not found'); process.exit(1); }
const ascii = (rule) => {
  const prefix = rule.startsWith('!') ? '!' : '';
  const labels = rule.replace(/^!/, '').split('.');
  const out = labels.map((l) => (l === '*' ? '*' : domainToASCII(l) || l));
  return prefix + out.join('.');
};
const rules = [...new Set(text.slice(start, end).split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//'))
  .map((l) => l.split(/\s/)[0].toLowerCase()).filter((r) => r.includes('.')).map(ascii))].sort();
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'packages/integrations/src/domains/psl-icann.ts');
const chunk = (list, n = 8) => { const o = []; for (let i = 0; i < list.length; i += n) o.push(`  ${list.slice(i, i + n).map((r) => `'${r}'`).join(', ')},`); return o; };
writeFileSync(out, `// GENERATED by scripts/providers/update-psl.mjs from the Public Suffix List — do not edit by hand.
// Source: https://publicsuffix.org/list/public_suffix_list.dat (ICANN section), VERSION ${version}, COMMIT ${commit}.
// Every multi-label ICANN rule ("com.eg", "*.ck", "!www.ck"), internationalised rules in punycode.
// The Public Suffix List is subject to the Mozilla Public License, v. 2.0 (https://mozilla.org/MPL/2.0/).
export const PSL_VERSION = '${version}';
export const PSL_RULES: readonly string[] = [
${chunk(rules).join('\n')}
];
`);
console.log(`wrote ${rules.length} ICANN rules (PSL ${version}) to ${path.relative(root, out)}`);
