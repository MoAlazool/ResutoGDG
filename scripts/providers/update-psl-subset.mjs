#!/usr/bin/env node
// Regenerates packages/integrations/src/domains/psl-subset.ts from the Public Suffix List (INT-27).
//
//   curl -sS https://publicsuffix.org/list/public_suffix_list.dat -o /tmp/psl.dat
//   node scripts/providers/update-psl-subset.mjs /tmp/psl.dat
//   pnpm --filter @resuto/integrations test   # psl.test.ts pins the rules Resuto depends on
//
// Only the ICANN section is used (private-domain rules such as github.io are not registries a restaurant buys an apex
// from). Only rules of the top-level domains in COVERED are bundled: single-label TLDs need no rule (the PSL default
// rule "*" already treats every unknown TLD as a public suffix), so the subset only has to carry the multi-label
// registry rules (com.eg, com.sa, co.uk …) of the countries Resuto sells in and their neighbours. A hostname under a
// TLD that has multi-label rules but is outside COVERED is resolved with the default rule and reported as such
// (pslCoverage: 'default_rule'); TLDs without any multi-label rule (com, net, app …) are exact with the default rule.
// The list is downloaded by a person; this script never fetches anything.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const COVERED = [
  // Resuto markets and the Gulf / Levant / North Africa neighbours.
  'eg', 'sa', 'ae', 'kw', 'qa', 'bh', 'om', 'jo', 'lb', 'iq', 'ps', 'sy', 'ye', 'ly', 'sd', 'tn', 'dz', 'ma', 'tr',
  // Common elsewhere for brand domains.
  // Large municipal rule sets (jp, no, it, us, pl, br) are left out on purpose: a restaurant there resolves with the
  // default rule and the domain page says so.
  'uk', 'au', 'nz', 'za', 'in', 'pk', 'my', 'sg', 'mx', 'ar', 'cn', 'hk', 'tw', 'kr', 'il', 'ir',
  'fr', 'de', 'es', 'nl', 'ch', 'at', 'be', 'se', 'dk', 'fi', 'ie', 'pt', 'gr', 'ca',
];

const [, , input] = process.argv;
if (!input) { console.error('usage: node scripts/providers/update-psl-subset.mjs <public_suffix_list.dat>'); process.exit(2); }
const text = readFileSync(input, 'utf8');
const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? 'unknown';
const commit = text.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? 'unknown';
const icann = text.slice(text.indexOf('// ===BEGIN ICANN DOMAINS==='), text.indexOf('// ===END ICANN DOMAINS==='));
if (!icann) { console.error('ICANN section not found'); process.exit(1); }
const covered = new Set(COVERED);
const all = icann.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('//')).map((l) => l.split(/\s/)[0].toLowerCase());
const tldOf = (r) => r.replace(/^!/, '').split('.').pop();
const rules = all.filter((r) => r.includes('.') && covered.has(tldOf(r))).sort();
// TLDs that DO have multi-label rules the subset leaves out: only these fall back to the default rule.
const uncovered = [...new Set(all.filter((r) => r.includes('.') && !covered.has(tldOf(r))).map(tldOf))].sort();
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'packages/integrations/src/domains/psl-subset.ts');
const chunk = (list, n = 8) => { const out = []; for (let i = 0; i < list.length; i += n) out.push(`  ${list.slice(i, i + n).map((r) => `'${r}'`).join(', ')},`); return out; };
const lines = chunk(rules);
writeFileSync(out, `// GENERATED by scripts/providers/update-psl-subset.mjs from the Public Suffix List — do not edit by hand.
// Source: https://publicsuffix.org/list/public_suffix_list.dat (ICANN section), VERSION ${version}, COMMIT ${commit}.
// Multi-label rules ("com.eg", "*.ck", "!www.ck") of the covered top-level domains only; see the script for why.
export const PSL_VERSION = '${version}';
export const PSL_COVERED_TLDS: readonly string[] = [${COVERED.map((t) => `'${t}'`).join(', ')}];
export const PSL_RULES: readonly string[] = [
${lines.join('\n')}
];
/** TLDs with multi-label registry rules that are NOT bundled: hostnames under them use the default rule. */
export const PSL_UNCOVERED_TLDS: readonly string[] = [
${chunk(uncovered).join('\n')}
];
`);
console.log(`wrote ${rules.length} rules (${COVERED.length} TLDs, PSL ${version}) to ${path.relative(root, out)}`);
