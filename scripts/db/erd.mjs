#!/usr/bin/env node
// Regenerates docs/architecture/DATABASE_ERD.md from the migrated database.
import { writeFileSync } from 'node:fs';
import pg from 'pg';

const DOMAINS = [
  ['Tenancy & platform', /^(organizations|branches|profiles|memberships|invitations|platform_admins|audit_logs|outbox_events|event_handlings|job_runs|idempotency_keys|legacy_id_map|media_assets)$/],
  ['Billing', /^(plans|plan_|module_prices|subscription|entitlement|platform_invoices|usage_events)/],
  ['Catalog & floor', /^(menus|menu_categories|products|product_|modifier_|floor_layouts|dining_tables)/],
  ['Orders, visits & reservations', /^(visits|orders|order_|service_requests|reservations)/],
  ['Customers & inventory', /^(customer|suppliers|inventory_items|stock_|recipe_components)/],
  ['Payments & finance', /^(bill_|checkout_sessions|payments|payment_allocations|refunds|reconciliation_|expense|expenses|financial_exports)/],
  ['Delivery', /^(drivers|driver_|delivery_)/],
  ['Compliance', /^(tax_profiles|fiscal_|government_submissions|compliance_)/],
  ['Connect & marketing', /^(messaging_channels|conversations|messages|ordering_sessions|message_templates|handoffs|segment|promotion|campaign|tracking_links|attribution_events|ad_campaign_reports)/],
  ['Studio', /^(websites|website_sections|custom_domains|creative_assets)/],
  ['Integrations', /^(integration_|webhook_inbox)/],
  ['Intelligence & MCP', /^(ai_|assistant_|mcp_)/],
];

const client = new pg.Client({ connectionString: process.env.DATABASE_URL || 'postgres://postgres@127.0.0.1:54329/resuto' });
await client.connect();
const cols = (await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
         exists (select 1 from information_schema.table_constraints tc join information_schema.key_column_usage k
                   on k.constraint_name = tc.constraint_name and k.table_schema = tc.table_schema
                  where tc.table_schema = 'public' and tc.table_name = c.table_name and tc.constraint_type = 'PRIMARY KEY'
                    and k.column_name = c.column_name) as pk
    from information_schema.columns c where c.table_schema = 'public' order by c.table_name, c.ordinal_position`)).rows;
const fks = (await client.query(`
  select tc.table_name as src, ccu.table_name as dst, kcu.column_name as col
    from information_schema.table_constraints tc
    join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
    join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name and ccu.table_schema = tc.table_schema
   where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public' and ccu.table_schema = 'public'`)).rows;
const rls = new Set((await client.query(`select relname from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity`)).rows.map((r) => r.relname));
await client.end();

const tables = [...new Set(cols.map((c) => c.table_name))];
const type = (c) => (c.data_type === 'USER-DEFINED' ? c.udt_name : c.data_type.replace(/ /g, '_').replace('timestamp_with_time_zone', 'timestamptz'));
let out = `# Database ERD\n\nGenerated by \`node scripts/db/erd.mjs\` from the migrated schema — do not edit by hand.\n\n`;
out += `${tables.length} tables; ${[...rls].length} with row-level security enabled. Every tenant table carries \`org_id\`; branch-scoped tables also carry \`branch_id\`. Money columns end in \`_minor\` (integer minor units).\n\n`;
const assigned = new Set();
for (const [title, re] of DOMAINS) {
  const group = tables.filter((t) => re.test(t) && !assigned.has(t));
  if (!group.length) continue;
  group.forEach((t) => assigned.add(t));
  out += `## ${title}\n\n\`\`\`mermaid\nerDiagram\n`;
  for (const t of group) {
    out += `  ${t} {\n`;
    for (const c of cols.filter((x) => x.table_name === t)) out += `    ${type(c)} ${c.column_name}${c.pk ? ' PK' : ''}\n`;
    out += `  }\n`;
  }
  const seen = new Set();
  for (const f of fks.filter((f) => group.includes(f.src) && group.includes(f.dst) && f.src !== f.dst)) {
    const k = `${f.dst}-${f.src}-${f.col}`;
    if (seen.has(k)) continue;
    seen.add(k);
    out += `  ${f.dst} ||--o{ ${f.src} : "${f.col}"\n`;
  }
  out += '```\n\n';
  const external = fks.filter((f) => group.includes(f.src) && !group.includes(f.dst) && f.dst !== 'organizations');
  if (external.length) out += `Cross-domain references: ${[...new Set(external.map((f) => `\`${f.src}.${f.col}\` → \`${f.dst}\``))].join(', ')}.\n\n`;
}
const rest = tables.filter((t) => !assigned.has(t));
if (rest.length) out += `## Other\n\n${rest.map((t) => `- \`${t}\``).join('\n')}\n`;
writeFileSync(new URL('../../docs/architecture/DATABASE_ERD.md', import.meta.url), out);
console.log(`wrote DATABASE_ERD.md (${tables.length} tables)`);
