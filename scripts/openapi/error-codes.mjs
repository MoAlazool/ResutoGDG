#!/usr/bin/env node
// Error-code registry generator (audit PS-20, docs/API_STYLE.md).
//
// Scans apps/api/src (tests excluded) for the codes the API raises: the first argument of new DomainError(...),
// invalid(...), conflict(...), gone(...) and the module-local helpers that build a DomainError from a literal
// code, and writes packages/contracts/src/error-codes.ts (DOMAIN_ERROR_CODES, sorted). Generic HTTP codes live in
// packages/contracts/src/api.ts (HTTP_ERROR_CODES) and are not repeated here.
//
//   node scripts/openapi/error-codes.mjs           rewrite the registry
//   node scripts/openapi/error-codes.mjs --check   exit 1 when the registry is out of date (CI, API test suite)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SRC = path.join(root, 'apps/api/src');
const OUT = path.join(root, 'packages/contracts/src/error-codes.ts');
const API_TS = path.join(root, 'packages/contracts/src/api.ts');

// Calls whose first argument is an error code. `skip`/`fail`/`refuse` are local helpers that wrap DomainError.
const CALLS = /\b(?:new\s+DomainError|new\s+SplitRuleError|invalid|conflict|gone|skip|fail|refuse|domainError|providerFailure)\(\s*/g;
const CODE = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)+$|^[a-z]{4,}$/;

function files(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) return files(p);
    return p.endsWith('.ts') && !p.endsWith('.test.ts') ? [p] : [];
  });
}

/** The text of the first call argument (up to the first top-level comma or closing paren). */
function firstArg(src, start) {
  let depth = 0;
  let quote = null;
  for (let i = start; i < src.length; i++) {
    const c = src[i];
    if (quote) { if (c === quote && src[i - 1] !== '\\') quote = null; continue; }
    if (c === "'" || c === '"' || c === '`') { quote = c; continue; }
    if (c === '(' || c === '[' || c === '{') depth++;
    else if (c === ')' || c === ']' || c === '}') { if (depth === 0) return src.slice(start, i); depth--; }
    else if (c === ',' && depth === 0) return src.slice(start, i);
  }
  return '';
}

export function scanErrorCodes() {
  const codes = new Set();
  for (const file of files(SRC)) {
    const src = readFileSync(file, 'utf8');
    for (const m of src.matchAll(CALLS)) {
      const arg = firstArg(src, m.index + m[0].length);
      for (const lit of arg.matchAll(/'([^'\\]+)'/g)) if (CODE.test(lit[1])) codes.add(lit[1]);
    }
  }
  return codes;
}

/** Keys of HTTP_ERROR_CODES, read from the contracts source (no build needed). */
function httpCodes() {
  const src = readFileSync(API_TS, 'utf8');
  const block = src.slice(src.indexOf('export const HTTP_ERROR_CODES'), src.indexOf('} as const satisfies'));
  return new Set([...block.matchAll(/^\s+([a-z_]+): \{ status:/gm)].map((m) => m[1]));
}

export function registry() {
  const generic = httpCodes();
  return [...scanErrorCodes()].filter((c) => !generic.has(c)).sort();
}

export function render(codes) {
  return `// GENERATED by scripts/openapi/error-codes.mjs from apps/api/src: do not edit by hand.
// Domain error codes the API can return (audit PS-20). Generic HTTP codes are HTTP_ERROR_CODES in ./api.ts.
// Regenerate with \`node scripts/openapi/error-codes.mjs\` after adding a code; the API suite fails on drift.
export const DOMAIN_ERROR_CODES = [
${codes.map((c) => `  '${c}',`).join('\n')}
] as const;
`;
}

export function check() {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* first run */ }
  return current === render(registry());
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    if (!check()) {
      console.error('packages/contracts/src/error-codes.ts is out of date: run node scripts/openapi/error-codes.mjs');
      process.exit(1);
    }
    console.log('error-code registry is up to date');
  } else {
    writeFileSync(OUT, render(registry()));
    console.log(`wrote ${path.relative(root, OUT)}`);
  }
}
